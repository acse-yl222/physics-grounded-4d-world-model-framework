    wall = ctx.mesh("Exact 169 exterior wall real estimated openings")
    trim = ctx.mesh("Estimated stone bands sash frames")
    roof = ctx.mesh("EA height zones and low return roof courts")
    door = ctx.mesh("Estimated west door finite stair and landing")

    def F(m, vs, mat):
        for i in range(1, len(vs) - 1):
            a, b, c = vs[0], vs[i], vs[i + 1]
            u = [b[k] - a[k] for k in range(3)]
            v = [c[k] - a[k] for k in range(3)]
            if (
                sum(
                    (u[(k + 1) % 3] * v[(k + 2) % 3] - u[(k + 2) % 3] * v[(k + 1) % 3]) ** 2
                    for k in range(3)
                )
                > 1e-12
            ):
                m.face([a, b, c], mat)

    entries = []
    count = 0
    for ri, r in enumerate([feature["geometry"][0]["outer"]] + [p["outer"] for p in ROOF["wells"]]):
        signed = sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(r, r[1:] + r[:1]))
        sg = (1 if signed > 0 else -1) * (1 if ri == 0 else -1)
        for ei, (origin, end) in enumerate(zip(r, r[1:] + r[:1])):
            L = math.dist(origin, end)
            tx, ty = (end[0] - origin[0]) / L, (end[1] - origin[1]) / L
            nx, ny = ty * sg, -tx * sg
            angle = math.atan2(ty, tx)

            def P(s, d, z):
                return (origin[0] + tx * s + nx * d, origin[1] + ty * s + ny * d, z + base)

            def B(m, s, d, z, w, dep, h, mat):
                m.box(*P(s, d, z), w, dep, h, mat, angle)

